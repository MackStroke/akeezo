async function seed() {
  // Always write to JSON file for local dev
  await mkdir(DATA_DIR, { recursive: true });
  const enriched = hospitals.map(h => ({
    ...h,
    _id: crypto.randomUUID(),
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  }));
  await writeFile(
    path.join(DATA_DIR, 'hospitals.json'),
    JSON.stringify(enriched, null, 2),
    'utf8',
  );
  console.log(`✓ Wrote ${enriched.length} sample hospitals to ${DATA_DIR}/hospitals.json`);

  // If MongoDB is available, also seed there
  if (process.env.MONGODB_URI) {
    const mongoose = await import('mongoose');
    await mongoose.default.connect(process.env.MONGODB_URI);
    const { Hospital } = await import('../models/Hospital.js');
    await Hospital.deleteMany({ isSample: true });
    await Hospital.insertMany(hospitals);
    console.log(`✓ Inserted ${hospitals.length} sample hospitals into MongoDB`);
    await mongoose.default.disconnect();
  }
}

seed().catch(err => {
  console.error('Seed failed:', err);
  process.exit(1);
});
